import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
import { readerBrowser } from "../paper-reader/browser.mjs";
await mkdir("/tmp/readflow-x8/screenshots", { recursive: true });
const env = await readerBrowser("?blocks&configured&x6&x8", "tests/paper-reader/integration-fixture.tsx");
const { page } = env;
try {
  await page.getByRole("option", { name: "Paper a", exact: true }).dblclick();
  await page.getByRole("tab", { name: "译文", exact: true }).click();
  const panel = page.getByLabel("本页译文", { exact: true });
  await panel.getByText("质检：2 块已自动重译，1 块仍需核对", { exact: true }).waitFor();
  await panel.getByRole("button", { name: "需核对", exact: true }).click();
  assert.equal(await panel.locator("[data-sidebar-block]").count(), 1);
  assert.equal(await panel.locator("strong").filter({ hasText: "任务。" }).evaluate((el) => getComputedStyle(el).fontWeight), "700");
  await panel.locator("summary").click();
  await panel.getByLabel("术语译法 1", { exact: true }).fill("控制策略");
  await panel.getByRole("button", { name: "保存术语", exact: true }).click();
  await panel.getByRole("button", { name: "按新术语重译相关块（1）", exact: true }).click();
  assert.equal(env.blocks.requests().at(-1).block_ids.length, 1);
  assert.equal(env.blocks.requests().at(-1).force, true);
  await page.screenshot({ path: "/tmp/readflow-x8/screenshots/terms-review.png" });
  await page.evaluate(() => window.fixture.wb.openSettings("translation"));
  await page.getByRole("heading", { name: "翻译", exact: true }).waitFor();
  const automatic = page.getByRole("checkbox", { name: "空闲时自动翻译新导入的文献", exact: true });
  assert.equal(await automatic.isChecked(), false);
  await automatic.check();
  assert.equal(await page.evaluate(() => window.fixture.wb.store.getSnapshot().autoTranslateImports), true);
  await page.getByLabel("原版式排版密度", { exact: true }).selectOption("compact");
  assert.equal(await page.evaluate(() => window.fixture.wb.store.getSnapshot().layoutDensity), "compact");
  await page.getByText(/产生 token 费用/).waitFor();
  await page.getByText(/产生 token 费用/).scrollIntoViewIfNeeded();
  await page.screenshot({ path: "/tmp/readflow-x8/screenshots/translation-settings.png" });
  await automatic.uncheck();
  await page.evaluate(() => window.fixture.wb.setPrefs({ theme: "dark" }));
  await page.screenshot({ path: "/tmp/readflow-x8/screenshots/translation-settings-dark.png" });
  assert.deepEqual(env.errors, []);
  assert.deepEqual(env.unexpected, []);
  console.log("PASS term editing/related retry and document-wide QA filter");
} finally { await env.browser.close(); }
