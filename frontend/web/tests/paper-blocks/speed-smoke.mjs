import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
import { readerBrowser } from "../paper-reader/browser.mjs";
const output = "/tmp/readflow-x3/screenshots";
await mkdir(output, { recursive: true });
const env = await readerBrowser("?blocks&configured&x3", "tests/paper-reader/integration-fixture.tsx");
try {
  const { page, blocks } = env;
  const button = (name) => page.getByRole("button", { name, exact: true });
  await page.getByRole("option", { name: "Paper a", exact: true }).dblclick();
  await page.locator("[data-paper-page] .pr-text-layer span").first().waitFor();
  const input = page.getByRole("spinbutton", { name: "页码" });
  await input.fill("2");
  await input.press("Enter");
  await page.waitForFunction(() => document.querySelector('[aria-label="页码"]').value === "2");
  await button("翻译全文").click();
  await page.getByText("翻译 35%", { exact: true }).first().waitFor();
  assert.equal(blocks.requests().at(-1).current_page, 2);
  assert.equal(blocks.requests().at(-1).translation.disable_thinking, true);
  assert.equal(blocks.requests().at(-1).translation.workers, 2);
  blocks.publishBatch();
  await page.getByText("翻译 55%", { exact: true }).first().waitFor();
  assert.equal(await button("块模式").getAttribute("aria-pressed"), "true");
  await button("知道了").click();
  await input.fill("1");
  await input.press("Enter");
  const span = page.locator('[data-paper-page="1"] .pr-text-layer span').filter({ hasText: "useful value" }).first();
  await span.click();
  const card = page.getByRole("dialog", { name: "块译文", exact: true });
  await card.getByText(/【首批译文】/).waitFor();
  blocks.publishBatch("【更新译文】");
  await card.getByText(/【更新译文】/).waitFor();
  await page.locator('[data-block-fallback="thinking"]').waitFor();
  await page.screenshot({ path: `${output}/incremental-light.png` });
  blocks.rendering();
  await page.getByText("正在排版译文 PDF 90%", { exact: true }).first().waitFor();
  await page.evaluate(() => window.fixture.wb.setPrefs({ theme: "dark" }));
  await page.screenshot({ path: `${output}/rendering-dark.png` });
  await card.getByRole("button", { name: "关闭", exact: true }).click();
  blocks.finish();
  await button("译文").waitFor();
  await button("译文").click();
  await page.locator('[data-paper-reader] canvas').first().waitFor();
  await page.evaluate(() => window.fixture.wb.openSettings("translation"));
  const toggle = page.getByRole("checkbox", { name: "翻译时关闭模型思考（更快、更省）" });
  assert.equal(await toggle.isChecked(), true);
  await toggle.uncheck();
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem("readflow.workbench.prefs.v1"))
    .translationDisableThinking), false);
  const workers = page.getByRole("spinbutton", { name: "翻译并发数" });
  assert.equal(await workers.getAttribute("max"), "16");
  await workers.fill("8");
  await button("保存").click();
  await page.screenshot({ path: `${output}/settings-dark.png` });
  await page.evaluate(() => window.fixture.wb.setPrefs({ theme: "light" }));
  await page.screenshot({ path: `${output}/settings-light.png` });
  await button("完成").click();
  await button("补翻／重新排版").click();
  await page.getByText("翻译 35%", { exact: true }).first().waitFor();
  assert.equal(blocks.requests().at(-1).translation.disable_thinking, false);
  assert.equal(blocks.requests().at(-1).translation.workers, 8);
  await button("取消翻译").click();
  await button("补翻／重新排版").waitFor();
  assert.deepEqual(env.errors, []);
  assert.deepEqual(env.unexpected, []);
  console.log("PASS: current-page payload, live batches/card refresh, compatibility notice, rendering, PDF, settings, cancellation");
} finally {
  await env.browser.close();
}
